/**
 * Draws a red triangle on a blue background in a browser, and prints what it drew.
 *
 * <p>It draws twice. The first time the triangle goes into a texture that is never shown (the same scene as the
 * desktop sample {@code triangle-offscreen}), with the corners generated by the shader. The second time it draws to
 * the page's canvas through a surface, with the corners uploaded from a Java {@code float[]} and the indices from a
 * direct {@link ByteBuffer}, which exercises both upload paths of the web backend. In both cases the pixels are read
 * back through a mapped buffer and printed with {@code console.log}, so a script can check them without a screen.
 *
 * <p>The browser cannot block, so every step that waits for the GPU continues in a callback.
 *
 */
final class WebTriangle {

  private static final int SIZE = 64;
  private static final int ROW_BYTES = 256;
  private static final long READBACK_BYTES = (long) ROW_BYTES * SIZE;

  private static final String SHADER = """
      @vertex fn vs(@builtin(vertex_index) i : u32) -> @builtin(position) vec4f {
        var p = array<vec2f, 3>(vec2f(0.0, 0.8), vec2f(-0.8, -0.8), vec2f(0.8, -0.8));
        return vec4f(p[i], 0.0, 1.0);
      }
      @fragment fn fs() -> @location(0) vec4f { return vec4f(1.0, 0.0, 0.0, 1.0); }
      """;

  private static final String BUFFER_SHADER = """
      @vertex fn vs(@location(0) p : vec2f) -> @builtin(position) vec4f { return vec4f(p, 0.0, 1.0); }
      @fragment fn fs() -> @location(0) vec4f { return vec4f(1.0, 0.0, 0.0, 1.0); }
      """;

  private static final float[] CORNERS = { 0.0f, 0.8f, -0.8f, -0.8f, 0.8f, -0.8f };

  private final byte[] pixels = new byte[(int) READBACK_BYTES];
  private final Context ctx;
  private final Report report;
  private final GpuDevice device;
  private final GpuQueue queue;
  private final GpuInstance instance;
  private final GpuAdapter adapter;

  private Runnable done;

  WebTriangle(Context ctx) {
    this.ctx = ctx;
    this.report = ctx.report;
    this.device = ctx.device;
    this.queue = ctx.queue;
    this.instance = ctx.instance;
    this.adapter = ctx.adapter;
  }

  void run(Runnable done) {
    this.done = done;
    drawOffscreen();
  }

  private void drawOffscreen() {
    GpuTextureDescriptor textureDescriptor = new GpuTextureDescriptor();
    textureDescriptor.usage = GpuTextureUsage.RENDER_ATTACHMENT | GpuTextureUsage.COPY_SRC;
    textureDescriptor.dimension = GpuTextureDimension.D2;
    textureDescriptor.size.width = SIZE;
    textureDescriptor.size.height = SIZE;
    textureDescriptor.format = GpuTextureFormat.RGBA8_UNORM;
    GpuTexture texture = device.createTexture(textureDescriptor);
    GpuTextureView view = texture.createView(null);

    GpuRenderPipeline pipeline = createPipeline(SHADER, GpuTextureFormat.RGBA8_UNORM, false);
    GpuBuffer readback = createReadback();

    GpuCommandEncoder encoder = device.createCommandEncoder(null);
    GpuRenderPassEncoder pass = beginPass(encoder, view);
    pass.setPipeline(pipeline);
    pass.draw(3, 1, 0, 0);
    pass.end();
    copyToBuffer(encoder, texture, readback);
    GpuCommandBuffer commands = encoder.finish(null);
    queue.submit(new GpuCommandBuffer[] { commands }, 1);

    read(readback, "offscreen", false, () -> {
      pass.release();
      encoder.release();
      commands.release();
      readback.release();
      pipeline.release();
      view.release();
      texture.release();
      drawToCanvas();
    });
  }

  private void drawToCanvas() {
    GpuSurfaceDescriptor surfaceDescriptor = new GpuSurfaceDescriptor();
    surfaceDescriptor.nextInChain = TeaVmSurfaceSourceCanvas.ofSelector("#canvas");
    GpuSurface surface = instance.createSurface(surfaceDescriptor);

    GpuSurfaceCapabilities capabilities = new GpuSurfaceCapabilities(2, 1, 2);
    surface.getCapabilities(adapter, capabilities);
    GpuTextureFormat format = capabilities.formats[0];
    Report.log("Canvas format: " + format);

    GpuSurfaceConfiguration configuration = new GpuSurfaceConfiguration();
    configuration.device = device;
    configuration.format = format;
    configuration.usage = GpuTextureUsage.RENDER_ATTACHMENT | GpuTextureUsage.COPY_SRC;
    configuration.width = SIZE;
    configuration.height = SIZE;
    surface.configure(configuration);

    GpuRenderPipeline pipeline = createPipeline(BUFFER_SHADER, format, true);
    GpuBuffer vertices = createBuffer(GpuBufferUsage.VERTEX | GpuBufferUsage.COPY_DST, 24);
    queue.writeBuffer(vertices, 0L, CORNERS, 0, CORNERS.length);
    ByteBuffer indexData = ByteBuffer.allocateDirect(8).order(ByteOrder.LITTLE_ENDIAN);
    indexData.putShort((short) 0).putShort((short) 1).putShort((short) 2).putShort((short) 0).flip();
    GpuBuffer indices = createBuffer(GpuBufferUsage.INDEX | GpuBufferUsage.COPY_DST, 8);
    queue.writeBuffer(indices, 0L, indexData);
    GpuBuffer readback = createReadback();

    GpuSurfaceTexture current = new GpuSurfaceTexture();
    surface.getCurrentTexture(current);
    GpuTextureView view = current.texture.createView(null);
    GpuCommandEncoder encoder = device.createCommandEncoder(null);
    GpuRenderPassEncoder pass = beginPass(encoder, view);
    pass.setPipeline(pipeline);
    pass.setVertexBuffer(0, vertices, 0L, GpuConstants.WHOLE_SIZE);
    pass.setIndexBuffer(indices, GpuIndexFormat.UINT16, 0L, GpuConstants.WHOLE_SIZE);
    pass.drawIndexed(3, 1, 0, 0, 0);
    pass.end();
    copyToBuffer(encoder, current.texture, readback);
    GpuCommandBuffer commands = encoder.finish(null);
    queue.submit(new GpuCommandBuffer[] { commands }, 1);
    surface.present();

    boolean bgra = format == GpuTextureFormat.BGRA8_UNORM;
    read(readback, "canvas", bgra, () -> {
      pass.release();
      encoder.release();
      commands.release();
      readback.release();
      vertices.release();
      indices.release();
      pipeline.release();
      view.release();
      current.texture.release();
      surface.unconfigure();
      surface.release();
      done.run();
    });
  }

  private GpuRenderPipeline createPipeline(String code, GpuTextureFormat format, boolean withBuffer) {
    GpuShaderSourceWGSL wgsl = new GpuShaderSourceWGSL();
    wgsl.code = code;
    GpuShaderModuleDescriptor shaderDescriptor = new GpuShaderModuleDescriptor();
    shaderDescriptor.nextInChain = wgsl;
    GpuShaderModule shader = device.createShaderModule(shaderDescriptor);

    GpuRenderPipelineDescriptor descriptor = new GpuRenderPipelineDescriptor();
    descriptor.vertex.module = shader;
    descriptor.vertex.entryPoint = "vs";
    if (withBuffer) {
      descriptor.vertex.bufferCount = 1;
      GpuVertexBufferLayout layout = descriptor.vertex.buffers[0];
      layout.arrayStride = 8L;
      layout.attributeCount = 1;
      GpuVertexAttribute attribute = layout.attributes[0];
      attribute.format = GpuVertexFormat.FLOAT32X2;
      attribute.offset = 0L;
      attribute.shaderLocation = 0;
    }
    GpuFragmentState fragment = new GpuFragmentState();
    fragment.module = shader;
    fragment.entryPoint = "fs";
    fragment.targetCount = 1;
    GpuColorTargetState target = fragment.targets[0];
    target.format = format;
    target.writeMask = GpuColorWriteMask.ALL;
    descriptor.fragment = fragment;
    GpuRenderPipeline pipeline = device.createRenderPipeline(descriptor);
    shader.release();
    return pipeline;
  }

  private GpuBuffer createBuffer(long usage, long size) {
    GpuBufferDescriptor descriptor = new GpuBufferDescriptor();
    descriptor.usage = usage;
    descriptor.size = size;
    return device.createBuffer(descriptor);
  }

  private GpuBuffer createReadback() {
    return createBuffer(GpuBufferUsage.MAP_READ | GpuBufferUsage.COPY_DST, READBACK_BYTES);
  }

  private GpuRenderPassEncoder beginPass(GpuCommandEncoder encoder, GpuTextureView view) {
    GpuRenderPassDescriptor pass = new GpuRenderPassDescriptor();
    pass.colorAttachmentCount = 1;
    GpuRenderPassColorAttachment color = pass.colorAttachments[0];
    color.view = view;
    color.loadOp = GpuLoadOp.CLEAR;
    color.storeOp = GpuStoreOp.STORE;
    color.clearValue.b = 1.0;
    color.clearValue.a = 1.0;
    return encoder.beginRenderPass(pass);
  }

  private void copyToBuffer(GpuCommandEncoder encoder, GpuTexture texture, GpuBuffer buffer) {
    GpuTexelCopyTextureInfo source = new GpuTexelCopyTextureInfo();
    source.texture = texture;
    source.aspect = GpuTextureAspect.ALL;
    GpuTexelCopyBufferInfo destination = new GpuTexelCopyBufferInfo();
    destination.buffer = buffer;
    destination.layout.bytesPerRow = ROW_BYTES;
    destination.layout.rowsPerImage = SIZE;
    GpuExtent3D extent = new GpuExtent3D();
    extent.width = SIZE;
    extent.height = SIZE;
    encoder.copyTextureToBuffer(source, destination, extent);
  }

  private void read(GpuBuffer buffer, String name, boolean bgra, Runnable next) {
    buffer.mapAsync(GpuMapMode.READ, 0L, READBACK_BYTES, GpuCallbackMode.ALLOW_SPONTANEOUS, (status, message) -> {
      if (status != GpuMapAsyncStatus.SUCCESS) {
        report.fail("Cannot map the " + name + " readback buffer (" + status + "): " + message);
      } else {
        GpuStatus read = buffer.readMappedRange(0L, pixels, 0, pixels.length);
        buffer.unmap();
        if (read != GpuStatus.SUCCESS) {
          report.fail("Cannot read the " + name + " pixels (" + read + ")");
        } else {
          report(name, bgra);
        }
      }
      next.run();
    });
  }

  private void report(String name, boolean bgra) {
    String center = pixel(SIZE / 2, SIZE / 2, bgra);
    String corner = pixel(1, 1, bgra);
    Report.log("PIXEL " + name + " center (r,g,b,a) = " + center);
    Report.log("PIXEL " + name + " corner (r,g,b,a) = " + corner);
    report.check(name + " triangle", center.equals("255,0,0,255") && corner.equals("0,0,255,255"),
        "center " + center + ", corner " + corner);
  }

  private String pixel(int x, int y, boolean bgra) {
    int at = y * ROW_BYTES + x * 4;
    int r = pixels[at + (bgra ? 2 : 0)] & 0xFF;
    int g = pixels[at + 1] & 0xFF;
    int b = pixels[at + (bgra ? 0 : 2)] & 0xFF;
    int a = pixels[at + 3] & 0xFF;
    return r + "," + g + "," + b + "," + a;
  }
}
