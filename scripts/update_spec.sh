#!/usr/bin/env bash
# Downloads the pinned webgpu-headers specification files into spec/.
#
# Usage: scripts/update_spec.sh <webgpu-headers commit sha> [<gpuweb commit sha>]
#
# The files are copied byte for byte from the given commit of
# https://github.com/webgpu-native/webgpu-headers. Never edit them by hand. After running this script,
# update spec/SPEC_VERSION.md (commit, Dawn commit, date) and review the generator test results.
#
# With a second argument, the browser WebIDL (spec/webgpu.idl) is refreshed as well. It is cut out of the
# specification source in https://github.com/gpuweb/gpuweb at that commit: every <script type=idl> block of
# spec/index.bs is copied in order, below a header that names the origin. Pass the same second argument again to
# keep the IDL where it is, or leave it out to leave the IDL file alone.

set -euo pipefail

if [ "$#" -lt 1 ] || [ "$#" -gt 2 ]; then
  echo "usage: $0 <webgpu-headers commit sha> [<gpuweb commit sha>]" >&2
  exit 1
fi

commit="$1"
idl_commit="${2:-}"
if ! [[ "$commit" =~ ^[0-9a-f]{40}$ ]]; then
  echo "error: expected a full 40 character commit sha, got '$commit'" >&2
  exit 1
fi

if [ -n "$idl_commit" ] && ! [[ "$idl_commit" =~ ^[0-9a-f]{40}$ ]]; then
  echo "error: expected a full 40 character commit sha, got '$idl_commit'" >&2
  exit 1
fi

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
spec_dir="$repo_root/spec"
base="https://raw.githubusercontent.com/webgpu-native/webgpu-headers/$commit"

# Each entry is "remote path:local name".
files=(
  "webgpu.json:webgpu.json"
  "schema.json:schema.json"
  "webgpu.h:webgpu.h"
  "LICENSE:LICENSE-webgpu-headers"
)

tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

# Download everything first so a failed download never leaves spec/ half updated.
for entry in "${files[@]}"; do
  remote="${entry%%:*}"
  local_name="${entry##*:}"
  echo "downloading $remote"
  curl --fail --silent --show-error --location "$base/$remote" --output "$tmp_dir/$local_name"
done

if [ -n "$idl_commit" ]; then
  gpuweb="https://raw.githubusercontent.com/gpuweb/gpuweb/$idl_commit"
  echo "downloading spec/index.bs and LICENSE.md of gpuweb"
  curl --fail --silent --show-error --location "$gpuweb/spec/index.bs" --output "$tmp_dir/index.bs"
  curl --fail --silent --show-error --location "$gpuweb/LICENSE.md" --output "$tmp_dir/LICENSE-gpuweb"
  {
    echo "// WebGPU WebIDL, extracted from the specification source of the W3C GPU for the Web Working Group."
    echo "// Origin: https://github.com/gpuweb/gpuweb at commit $idl_commit (spec/index.bs)."
    echo "//"
    echo "// Copyright (C) World Wide Web Consortium (Massachusetts Institute of Technology, European Research"
    echo "// Consortium for Informatics and Mathematics, Keio University, Beihang). All Rights Reserved."
    echo "// This work is distributed under the W3C Software and Document License and the GPU for the Web"
    echo "// 3-Clause BSD License; see LICENSE-gpuweb next to this file."
    echo "//"
    echo "// This file is generated by scripts/update_spec.sh. Do not edit it by hand."
    awk '
      /<script type=idl[^>]*>/ { inside = 1; next }
      /<\/script>/ { if (inside) { inside = 0; print "" } ; next }
      inside { print }
    ' "$tmp_dir/index.bs"
  } > "$tmp_dir/webgpu.idl"
  if ! grep -q 'interface GPUDevice' "$tmp_dir/webgpu.idl"; then
    echo "error: the extracted IDL looks empty" >&2
    exit 1
  fi
fi

for entry in "${files[@]}"; do
  local_name="${entry##*:}"
  mv "$tmp_dir/$local_name" "$spec_dir/$local_name"
done

if [ -n "$idl_commit" ]; then
  mv "$tmp_dir/webgpu.idl" "$spec_dir/webgpu.idl"
  mv "$tmp_dir/LICENSE-gpuweb" "$spec_dir/LICENSE-gpuweb"
  echo "updated $spec_dir/webgpu.idl to gpuweb $idl_commit"
fi

echo "updated $spec_dir to webgpu-headers $commit"
echo "next: edit spec/SPEC_VERSION.md and run ./gradlew :jwebgpu-test:test"
